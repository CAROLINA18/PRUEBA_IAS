CREATE TABLE IF NOT EXISTS pre_approved (
    id VARCHAR(40) PRIMARY KEY,
    customer_id VARCHAR(40) NOT NULL,
    status VARCHAR(20) NOT NULL,
    available_amount DECIMAL(19, 2) NOT NULL,
    CONSTRAINT chk_pre_approved_amount CHECK (available_amount >= 0)
);

CREATE TABLE IF NOT EXISTS usage_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_reference VARCHAR(80) NOT NULL,
    pre_approved_id VARCHAR(40) NOT NULL,
    customer_id VARCHAR(40) NOT NULL,
    amount DECIMAL(19, 2),
    status VARCHAR(20) NOT NULL,
    rejection_reason VARCHAR(240),
    processed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    remaining_amount DECIMAL(19, 2),
    CONSTRAINT uq_usage_request_reference UNIQUE (request_reference)
);

CREATE INDEX IF NOT EXISTS idx_usage_request_processed_at
    ON usage_request(processed_at DESC);

